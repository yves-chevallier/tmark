//! The CommonMark suite through the HTML writer (design 10-testing.md §2).
//! The examples are read from the vendored suite in
//! `crates/tmark-markdown/tests/commonmark.rs`; the ones listed in
//! `PASSING` render byte for byte as the reference implementation does.
//! The others are TMark's X-class deviations (`__x__`, `~x~`, `@word`,
//! `#[`, `---` … see the spec) or constructs the IR does not carry (raw
//! HTML blocks, entity references, image titles); the test prints the
//! score so a regression or a gain is visible.
//!
//! The fifteen "Emphasis and strong emphasis" examples whose whole
//! paragraph is one strong span are a deviation of the same kind: the
//! `paragraph.lead` feature (on by default, spec §Para) reads that shape
//! as a lead-in, so the HTML writer marks it `<strong class="lead">`.

use std::fs;
use std::path::Path;

use tmark_registry::{resolve, MemoryLoader, ResolveOptions};
use tmark_writers::{write, Backend, Media, WriterOptions};

/// `(input, expected, name)` triples of the suite file.
fn examples() -> Vec<(String, String, String)> {
    let path = Path::new(env!("CARGO_MANIFEST_DIR")).join("../tmark-markdown/tests/commonmark.rs");
    let text = fs::read_to_string(path).unwrap();
    let mut literals = Vec::new();
    let mut rest = text.as_str();
    while let Some(start) = rest.find("r###\"") {
        let after = &rest[start + 5..];
        let Some(end) = after.find("\"###") else {
            break;
        };
        literals.push(after[..end].to_string());
        rest = &after[end + 4..];
    }
    literals
        .chunks_exact(3)
        .map(|c| (c[0].clone(), c[1].clone(), c[2].clone()))
        .collect()
}

fn render(input: &str) -> String {
    let parsed = tmark_syntax::parse(input, tmark_ir::FileId::default());
    let resolved = resolve(
        &parsed.document,
        &MemoryLoader::new(),
        &ResolveOptions::default(),
    );
    let opts = WriterOptions {
        media: Media::Web,
        ..WriterOptions::default()
    };
    write(&parsed.document, &resolved, Backend::Html, &opts).text
}


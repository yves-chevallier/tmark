#[test]
fn commonmark_examples() {
    let examples = examples();
    assert!(examples.len() > 500, "suite found: {}", examples.len());
    let mut passed = Vec::new();
    let mut failed_expected = Vec::new();
    for (input, expected, name) in &examples {
        let got = render(input);
        if got == *expected {
            passed.push(name.as_str());
        } else if PASSING.contains(&name.as_str()) {
            failed_expected.push(format!("{name}\n--- expected\n{expected}--- got\n{got}"));
        }
    }
    eprintln!(
        "commonmark: {} of {} examples identical",
        passed.len(),
        examples.len()
    );
    if std::env::var_os("TMARK_COMMONMARK_LIST").is_some() {
        for name in &passed {
            eprintln!("PASS {name}");
        }
    }
    if std::env::var_os("TMARK_COMMONMARK_FAILS").is_some() {
        for (input, expected, name) in &examples {
            let got = render(input);
            if got != *expected {
                eprintln!("FAIL {name}\n--- input\n{input}--- expected\n{expected}--- got\n{got}");
            }
        }
    }
    assert!(
        failed_expected.is_empty(),
        "examples that used to pass:\n{}",
        failed_expected.join("\n")
    );
    for name in PASSING {
        assert!(
            passed.contains(name),
            "`{name}` is listed as passing but did not render"
        );
    }
}
